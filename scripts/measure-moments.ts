// Measure the Ear Test moments from the real videos with the app's own analysis,
// and write src/eartest/moments.ts. Run: node scripts/measure-moments.ts
import { spawn } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { analyzeFrame } from '../src/analysis/features.ts'
import type { AnalysisOptions, FrameFeatures, FramePlanes } from '../src/analysis/types.ts'
import { AEROSOL_CLASSES } from '../src/mapping/aerosols.ts'
import { CO2_CLASSES } from '../src/mapping/co2.ts'
import { NIGHT_CLASSES, YEAR_CHANGES } from '../src/mapping/nightLights.ts'
import { describeCo2 } from '../src/tracks/co2.ts'
import { formatDate, labelAt, parseLabels } from '../src/tracks/labels.ts'

const MEDIA = new URL('../public/media/', import.meta.url).pathname

function frames(file: string, height: number, options: Partial<AnalysisOptions>, onFrame: (f: FrameFeatures, t: number) => void): Promise<void> {
  const W = 160
  return new Promise((resolve) => {
    const ff = spawn('ffmpeg', ['-v', 'error', '-i', MEDIA + file, '-vf', `scale=${W}:${height}:flags=area`, '-r', '30', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'], { stdio: ['ignore', 'pipe', 'inherit'] })
    let buf = Buffer.alloc(0)
    let prev: FramePlanes | null = null
    let i = 0
    ff.stdout.on('data', (d: Buffer) => {
      buf = buf.length ? Buffer.concat([buf, d]) : d
      const size = W * height * 4
      let off = 0
      while (buf.length - off >= size) {
        const b = Buffer.from(buf.subarray(off, off + size))
        const r = analyzeFrame({ data: new Uint8ClampedArray(b.buffer, b.byteOffset, size), width: W, height }, prev, options)
        prev = r.planes
        onFrame(r.features, i / 30)
        i++
        off += size
      }
      buf = buf.subarray(off)
    })
    ff.on('close', () => resolve())
  })
}

/** Average a per-frame value over windows of `seconds`, centred on each window. */
async function windows(file: string, height: number, options: Partial<AnalysisOptions>, seconds: number, value: (f: FrameFeatures) => number) {
  const sums = new Map<number, [number, number]>()
  await frames(file, height, options, (f, t) => {
    const k = Math.floor(t / seconds)
    const s = sums.get(k) ?? [0, 0]
    s[0] += value(f)
    s[1]++
    sums.set(k, s)
  })
  return [...sums].filter(([, [, n]]) => n >= seconds * 25).map(([k, [sum, n]]) => ({ time: +(k * seconds + seconds / 2).toFixed(2), value: sum / n }))
}

const labels = parseLabels(readFileSync(MEDIA + 'lightning-flat.labels.txt', 'utf8'), [{ from: 2003, to: 2023 }])
const lightning = (await windows('lightning-flat.mp4', 80, { signal: 'yellow', riseThreshold: 0.04, signalFloor: 0.05 }, 2, (f) => f.risingPixels.length))
  .filter((m) => m.time > 2).map((m) => ({ ...m, label: formatDate(labelAt(labels, m.time, 60)!) }))
const co2 = (await windows('co2.mp4', 90, { classes: CO2_CLASSES, masks: [{ x: 0.79, y: 0.93, width: 0.2, height: 0.045 }] }, 2, (f) => f.classes.hot.amount * 100))
  .map((m) => ({ ...m, label: describeCo2(m.time).text.replace(/, \d\d:00$/, '') }))
const aerosols = (await windows('aerosols.mp4', 80, { classes: AEROSOL_CLASSES, masks: [{ x: 0.665, y: 0.895, width: 0.225, height: 0.09 }] }, 3, (f) => f.classes.dust.amount * 100))
  .map((m) => ({ ...m, label: `${Math.round(m.time)} s into the clip` }))
// Night lights: one moment per year, sampled in the middle of each year's span.
const yearStarts = [0, ...YEAR_CHANGES]
const nightRaw: { time: number; value: number }[] = []
await frames('night-lights.mp4', 90, { classes: NIGHT_CLASSES, masks: [{ x: 0.005, y: 0.49, width: 0.175, height: 0.115 }] }, (f, t) => nightRaw.push({ time: t, value: f.classes.lights.amount * 1000 }))
const night = yearStarts.map((start, i) => {
  const end = i + 1 < yearStarts.length ? yearStarts[i + 1] : 8.9
  const inYear = nightRaw.filter((r) => r.time >= start + 0.1 && r.time < end - 0.1)
  return { time: +((start + end) / 2).toFixed(2), value: inYear.reduce((a, b) => a + b.value, 0) / inYear.length, label: String(2012 + i) }
})

const round = (list: { time: number; value: number; label: string }[]) => list.map((m) => ({ ...m, value: +m.value.toFixed(3) }))
const out = `// Generated by scripts/measure-moments.ts from the videos in public/media. Do not edit by hand.
import type { MomentSet } from './types.ts'

export const MOMENT_SETS: MomentSet[] = ${JSON.stringify([
  { trackId: 'lightning', question: 'lightning', unit: 'newly lit pixels per frame', moments: round(lightning) },
  { trackId: 'aerosols', question: 'dust in the air', unit: 'per cent of the map covered by dust', moments: round(aerosols) },
  { trackId: 'night-lights', question: 'city light around the world', unit: 'lit pixels per thousand', moments: round(night) },
  { trackId: 'co2', question: 'high carbon dioxide in view', unit: 'per cent of the view in orange or red', moments: round(co2) },
], null, 2)}
`
writeFileSync(new URL('../src/eartest/moments.ts', import.meta.url), out)
console.log(`lightning ${lightning.length}, aerosols ${aerosols.length}, night ${night.length}, co2 ${co2.length}`)
for (const [n, l] of [['lightning', lightning], ['aerosols', aerosols], ['night', night], ['co2', co2]] as const) console.log(n, 'range', Math.min(...l.map((m) => m.value)).toFixed(3), Math.max(...l.map((m) => m.value)).toFixed(3))
