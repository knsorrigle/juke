// Measure how busy each video is, second by second, with the app's own analysis,
// and write src/tracks/activity.ts for the scrubber. Run: node scripts/measure-activity.ts
import { spawn } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { analyzeFrame } from '../src/analysis/features.ts'
import type { AnalysisOptions, FrameFeatures, FramePlanes } from '../src/analysis/types.ts'
import { AEROSOL_CLASSES } from '../src/mapping/aerosols.ts'
import { CO2_CLASSES } from '../src/mapping/co2.ts'
import { NIGHT_CLASSES } from '../src/mapping/nightLights.ts'

const MEDIA = new URL('../public/media/', import.meta.url).pathname

function perSecond(file: string, height: number, options: Partial<AnalysisOptions>, value: (f: FrameFeatures) => number): Promise<number[]> {
  const W = 160
  return new Promise((resolve) => {
    const ff = spawn('ffmpeg', ['-v', 'error', '-i', MEDIA + file, '-vf', `scale=${W}:${height}:flags=area`, '-r', '30', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'], { stdio: ['ignore', 'pipe', 'inherit'] })
    let buf = Buffer.alloc(0)
    let prev: FramePlanes | null = null
    let i = 0
    const sums: number[] = []
    const counts: number[] = []
    ff.stdout.on('data', (d: Buffer) => {
      buf = buf.length ? Buffer.concat([buf, d]) : d
      const size = W * height * 4
      let off = 0
      while (buf.length - off >= size) {
        const b = Buffer.from(buf.subarray(off, off + size))
        const r = analyzeFrame({ data: new Uint8ClampedArray(b.buffer, b.byteOffset, size), width: W, height }, prev, options)
        prev = r.planes
        const s = Math.floor(i / 30)
        sums[s] = (sums[s] ?? 0) + value(r.features)
        counts[s] = (counts[s] ?? 0) + 1
        i++
        off += size
      }
      buf = buf.subarray(off)
    })
    ff.on('close', () => {
      const raw = sums.map((v, k) => v / counts[k])
      const max = Math.max(...raw, 1e-9)
      resolve(raw.map((v) => +(v / max).toFixed(3)))
    })
  })
}

const total = (f: FrameFeatures) => Object.values(f.classes).reduce((a, c) => a + c.amount, 0)
const activity = {
  // Newly lit lightning pixels.
  lightning: await perSecond('lightning-flat.mp4', 80, { signal: 'yellow', riseThreshold: 0.04, signalFloor: 0.05 }, (f) => f.risingPixels.length),
  // All four aerosol types together.
  aerosols: await perSecond('aerosols.mp4', 80, { classes: AEROSOL_CLASSES, masks: [{ x: 0.665, y: 0.895, width: 0.225, height: 0.09 }] }, total),
  // How much the currents move.
  'sea-surface-currents': await perSecond('sea-surface-currents.mp4', 80, {}, (f) => f.diff),
  // City lights, then growth and loss.
  'night-lights': await perSecond('night-lights.mp4', 90, { classes: NIGHT_CLASSES, masks: [{ x: 0.005, y: 0.49, width: 0.175, height: 0.115 }] }, total),
  // Orange and red carbon dioxide in view.
  co2: await perSecond('co2.mp4', 90, { classes: CO2_CLASSES, masks: [{ x: 0.79, y: 0.93, width: 0.2, height: 0.045 }] }, total),
}
writeFileSync(
  new URL('../src/tracks/activity.ts', import.meta.url),
  `// Generated by scripts/measure-activity.ts from the videos in public/media. Do not edit by hand.
/** How busy each track is in each second of its video, 0..1 (1 = its busiest second). */
export const ACTIVITY: Record<string, number[]> = ${JSON.stringify(activity)}
`,
)
for (const [k, v] of Object.entries(activity)) console.log(k, v.length, 's, min', Math.min(...v), 'mean', (v.reduce((a, b) => a + b, 0) / v.length).toFixed(2))
